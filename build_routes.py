def main():
    data = json.loads(DATA.read_text(encoding="utf-8"))
    companies = [n for n in data["nodes"] if n["type"] == "company"]
    ids = {n["id"] for n in companies}

    missing = sorted(ids - set(ASSIGN))
    extra = sorted(set(ASSIGN) - ids)
    bad_route = sorted({v[0] for v in ASSIGN.values()} - set(GROUP_OF))
    if missing or extra or bad_route:
        print("!! 校验失败")
        if missing: print("   未分派:", missing)
        if extra: print("   不存在的 id:", extra)
        if bad_route: print("   未登记的路线:", bad_route)
        sys.exit(1)

    out = {
        "meta": {
            "version": "1.0",
            "date": "2026-10-09",
            "source_report": "docs/tech-route-report.md",
            "rule": "每条企业节点分派唯一主路线；判定规则见报告 1.3 节 R1-R7",
            "total": len(ids),
        },
        "groups": GROUP_ORDER,
        "route_order": ROUTE_ORDER,
        "group_of": GROUP_OF,
        "routes": {},
    }
    for nid, (route, conf, basis, note) in ASSIGN.items():
        out["routes"][nid] = {
            "route": route,
            "route_group": GROUP_OF[route],
            "confidence": conf,
            "basis": basis,
            "route_note": note,
        }

    (BASE / "tech_routes.json").write_text(
        json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")

    # 分布统计
    from collections import Counter
    c = Counter(v["route"] for v in out["routes"].values())
    g = Counter(v["route_group"] for v in out["routes"].values())
    print("tech_routes.json written | companies:", len(ids))
    for grp in GROUP_ORDER:
        print("  [%s] %d 家" % (grp, g[grp]))
        for r in ROUTE_ORDER:
            if GROUP_OF[r] == grp:
                print("      %-14s %d" % (r, c[r]))
    conf = Counter(v["confidence"] for v in out["routes"].values())
    print("  置信度:", dict(conf))


